
from datetime import datetime, timezone


def generate_report(filename, findings, ai_analysis=None):
    """Generate a combined deterministic and AI audit report."""

    errors = sum(
        1 for item in findings
        if item["severity"] == "error"
    )

    warnings = sum(
        1 for item in findings
        if item["severity"] == "warning"
    )

    info = sum(
        1 for item in findings
        if item["severity"] == "info"
    )

    lines = [
        "# DocuGuard Audit Report",
        "",
        f"**Audited file:** `{filename}`",
        f"**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        "## Deterministic Audit Summary",
        "",
        f"- Total findings: {len(findings)}",
        f"- Errors: {errors}",
        f"- Warnings: {warnings}",
        f"- Informational: {info}",
        "",
        "## Deterministic Findings",
        ""
    ]

    if not findings:
        lines.append("No deterministic documentation issues detected.")
    else:
        for index, finding in enumerate(findings, start=1):
            location = (
                f"Line {finding['line']}"
                if finding["line"] is not None
                else "Document level"
            )

            lines.extend([
                f"### {index}. {finding['category']}",
                "",
                f"**Severity:** {finding['severity'].upper()}",
                f"**Location:** {location}",
                "",
                f"**Issue:** {finding['message']}",
                "",
                f"**Suggestion:** {finding['suggestion']}",
                ""
            ])

    lines.extend([
        "---",
        "",
        "## AI-Assisted Analysis",
        ""
    ])

    if ai_analysis is None:
        lines.append("AI analysis was not requested.")
    else:
        lines.extend([
            f"**AI Summary:** {ai_analysis['summary']}",
            "",
            "**AI Suggestions**",
            ""
        ])

        suggestions = ai_analysis["suggestions"]

        if not suggestions:
            lines.append("No additional AI suggestions generated.")
        else:
            for index, item in enumerate(suggestions, start=1):
                lines.extend([
                    f"### AI Suggestion {index}: {item['category']}",
                    "",
                    f"**Severity:** {item['severity'].upper()}",
                    f"**Technical Risk:** {item['technical_risk'].upper()}",
                    "",
                    f"**Original text:** {item['original_text']}",
                    "",
                    f"**Issue:** {item['issue']}",
                    "",
                    f"**Suggested improvement:** {item['suggestion']}",
                    "",
                    "**Human review required:** Yes",
                    ""
                ])

    lines.extend([
        "---",
        "",
        "## Important Disclaimer",
        "",
        "Deterministic findings are generated through predefined "
        "validation rules.",
        "",
        "AI-generated suggestions are advisory and may contain "
        "inaccuracies.",
        "",
        "No AI suggestion is automatically approved or applied.",
        "Human verification is required before making changes.",
        "",
        "*Generated by DocuGuard.*"
    ])

    return "\n".join(lines)
