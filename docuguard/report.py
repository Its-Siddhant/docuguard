
from datetime import datetime, timezone


def generate_report(filename, findings):
    """Generate a Markdown documentation audit report."""

    total = len(findings)

    errors = sum(
        1 for item in findings
        if item["severity"] == "error"
    )

    warnings = sum(
        1 for item in findings
        if item["severity"] == "warning"
    )

    info = sum(
        1 for item in findings
        if item["severity"] == "info"
    )

    lines = [
        "# DocuGuard Audit Report",
        "",
        f"**Audited file:** `{filename}`",
        f"**Generated:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        "",
        "## Audit Summary",
        "",
        f"- Total findings: {total}",
        f"- Errors: {errors}",
        f"- Warnings: {warnings}",
        f"- Informational: {info}",
        "",
        "## Detailed Findings",
        ""
    ]

    if not findings:
        lines.append("No documentation issues detected.")
    else:
        for index, finding in enumerate(findings, start=1):
            location = (
                f"Line {finding['line']}"
                if finding["line"] is not None
                else "Document level"
            )

            lines.extend([
                f"### {index}. {finding['category']}",
                "",
                f"**Severity:** {finding['severity'].upper()}",
                f"**Location:** {location}",
                "",
                f"**Issue:** {finding['message']}",
                "",
                f"**Suggestion:** {finding['suggestion']}",
                ""
            ])

    lines.extend([
        "---",
        "",
        "## Important Disclaimer",
        "",
        "This report contains automated documentation checks.",
        "Suggestions are advisory and should be reviewed by a human.",
        "Technical accuracy is not guaranteed by these checks.",
        "",
        "*Generated by DocuGuard.*"
    ])

    return "\n".join(lines)
